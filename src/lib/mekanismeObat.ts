/**
 * Obat yang disebut di dalam satu teks tatalaksana.
 *
 * Pencocokan memakai BATAS KATA, bukan sekadar potongan teks: tanpa itu "Fe"
 * cocok dengan "Fenitoin" dan "besi" muncul pada setiap entri yang menyebut
 * "pembesian". Nama terpanjang diuji lebih dahulu supaya "asam traneksamat"
 * tidak keburu tertangkap oleh "asam folat".
 */
export function obatDalam(teks: string): MekanismeObat[] {
  const t = teks.toLowerCase()
  const keluar: MekanismeObat[] = []
  for (const o of MEKANISME_OBAT) {
    const nama = [o.nama, ...(o.alias ?? [])].sort((a, b) => b.length - a.length)
    const ketemu = nama.some((n) => {
      const k = n.toLowerCase()
      const i = t.indexOf(k)
      if (i < 0) return false
      const sebelum = i === 0 ? ' ' : t[i - 1]
      const sesudah = i + k.length >= t.length ? ' ' : t[i + k.length]
      return !/[a-z0-9]/.test(sebelum) && !/[a-z0-9]/.test(sesudah)
    })
    if (ketemu) keluar.push(o)
  }
  return keluar
}
