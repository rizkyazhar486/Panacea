import fs from 'fs';
import path from 'path';

const specialties = [
  'infectious', 'pulmonology', 'hepatology', 'nephrology', 'endocrinology',
  'rheumatology', 'hematology', 'immunology', 'orthopedics', 'ophthalmology',
  'otorhinolaryngology', 'urology', 'gynecology', 'obstetrics', 'pediatrics',
  'geriatrics', 'psychiatry', 'neurology', 'neurosurgery', 'cardiology',
  'cardiotoracic', 'dermatology', 'plastic-surgery', 'emergency', 'critical-care',
  'palliative', 'radiology', 'pathology', 'toxicology', 'pharmacology'
];

console.log('🚀 Generating scalable clinical modules...');

let createdCount = 0;
for (let i = 1; i <= 35; i++) {
  for (const specialty of specialties) {
    // Hyphen is not legal in a TS identifier: derive the identifier separately from the file name.
    const identBase = specialty.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
    const modName = `${identBase}Module${i}`;
    const fileName = `${specialty}Module${i}`;
    const dir = path.join('src', 'domains', 'generated-scale', specialty);
    fs.mkdirSync(dir, { recursive: true });

    const codeContent = `/**
 * PanaceaMed Generated Enterprise Module: ${modName}
 * Domain: ${specialty}
 * Directive Scale: Enterprise Autogenerated Core
 */
export interface ${modName}Input {
  patientId: string;
  clinicalMetricValue: number;
  timestamp: string;
}

export function evaluate${modName}(input: ${modName}Input) {
  const normalized = Number((input.clinicalMetricValue * 1.05).toFixed(2));
  let status = 'OPTIMAL_RANGE';
  if (normalized > 150) {
    status = 'ELEVATED_THRESHOLD_WARNING';
  } else if (normalized < 10) {
    status = 'CRITICAL_DEFICIT';
  }
  return {
    moduleId: '${modName}',
    patientId: input.patientId,
    processedValue: normalized,
    evaluationStatus: status,
    isClinicallyAuthoritative: false
  };
}
`;

    fs.writeFileSync(path.join(dir, `${fileName}.ts`), codeContent);
    createdCount++;
  }
}

console.log(`✅ Successfully generated ${createdCount} enterprise modules across specialized medical domains.`);
