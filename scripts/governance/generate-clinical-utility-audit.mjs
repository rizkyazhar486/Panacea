// Compute Priority Score: (Human impact * Workflow fit * Evidence readiness * Testability) / Implementation effort
function computePriority(entry) {
  const sc = entry.scorecard
  const humanImpact = sc.problemRelevance
  const workflowFit = sc.workflowIntegration
  const evidenceReadiness = sc.scientificEvidence
  const testability = sc.independentTestability
  const effort = Math.max(1, 6 - sc.resourceFeasibility) // High feasibility = lower implementation effort
  const rawScore = (humanImpact * workflowFit * evidenceReadiness * testability) / effort
  return Number(rawScore.toFixed(2))
}

