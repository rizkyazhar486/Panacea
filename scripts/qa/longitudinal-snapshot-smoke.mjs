import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '@playwright/test')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
try {
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    localStorage.clear()
    localStorage.setItem('panaceamed.session.v1', JSON.stringify({ account: { id: 'qa-account', email: 'qa@localhost.test', name: 'Snapshot QA', role: 'dokter', patientId: 'p1', isSubscriber: false, loggedAt: new Date().toISOString() }, loginAt: Date.now() }))
  })
  await page.goto(`${process.env.LONGITUDINAL_QA_ORIGIN || 'http://127.0.0.1:5180'}/scripts/qa/longitudinal-fixture.html`)
  await page.locator('[data-consumer]').first().waitFor()
  const read = () => page.locator('[data-consumer]').evaluateAll(nodes => nodes.map(n => ({ identity: n.dataset.identity, revision: Number(n.dataset.revision), subject: n.dataset.subject, events: JSON.parse(n.textContent) })))
  const initial = await read()
  assert.equal(initial.length, 3)
  assert.equal(new Set(initial.map(s => s.identity)).size, 1, 'three mounted consumers must share the same snapshot object')
  await page.getByText('Unrelated setting', { exact: true }).click()
  assert.deepEqual(await read(), initial, 'unrelated app state must not rebuild')
  await page.evaluate(async () => {
    dispatchEvent(new StorageEvent('storage', { key: 'pmd_unrelated_preference' }))
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  })
  assert.deepEqual(await read(), initial, 'unrelated cross-tab storage must not rebuild or refetch')
  await page.getByText('Change lab', { exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-consumer]').textContent.includes('lab.gdp'))
  const lab = await read()
  assert.equal(new Set(lab.map(s => s.identity)).size, 1)
  assert.equal(lab[0].revision, initial[0].revision + 1, 'one source revision causes one shared rebuild')
  assert.notEqual(lab[0].identity, initial[0].identity)
  await page.getByText('Change vitals', { exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-consumer]').textContent.includes('76'))
  assert((await read())[0].revision > lab[0].revision)
  await page.getByText('Switch patient', { exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-consumer]').dataset.subject === 'p2')
  for (const s of await read()) assert.deepEqual(s.events, [], 'new patient must not inherit previous labs/vitals')
  await page.evaluate(async () => {
    dispatchEvent(new Event('panacea:lab'))
    dispatchEvent(new CustomEvent('panacea:data-updated', { detail: { domains: ['health'], source: 'qa', at: Date.now() } }))
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  })
  for (const s of await read()) assert.deepEqual(s.events, [], 'unscoped local notifications cannot reassign the previous patient data')
  await page.getByText('Logout', { exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-consumer]').dataset.subject === '')
  for (const s of await read()) assert.deepEqual(s.events, [])

  // Offline/local login still promises device-local persistence. It must receive
  // a stable account/subject identity before personal lab/vital caches are usable.
  await page.getByText('Local patient login', { exact: true }).click()
  const localSession = await page.evaluate(() => JSON.parse(localStorage.getItem('panaceamed.session.v1')))
  assert.ok(localSession?.account?.id, 'local patient login must persist a stable account id')
  assert.ok(localSession?.account?.patientId, 'local patient login must persist a stable patient id')
  await page.getByText('Change lab', { exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-consumer]').textContent.includes('lab.gdp'))
  assert.deepEqual(errors, [])
  console.log('Three real React consumers: identical snapshot, one rebuild per lab revision, no rebuild for settings, live vital update, patient/logout isolation passed')
} finally { await browser.close() }
