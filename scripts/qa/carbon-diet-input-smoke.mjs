import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '@playwright/test')
const origin = process.env.CARBON_DIET_QA_ORIGIN || 'http://127.0.0.1:4173'
const output = process.env.CARBON_DIET_QA_OUTPUT || 'artifacts/carbon-diet-inputs'
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
const session = id => ({ account: { id, patientId: `self-${id}`, email: `${id}@localhost.test`, name: id, role: 'pasien', isSubscriber: false, loggedAt: new Date().toISOString() }, loginAt: Date.now() })
const scopedKey = id => `pmd_carbon_diet_v1:scope_v1:${encodeURIComponent(JSON.stringify([id, `self-${id}`]))}`
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(origin, { waitUntil: 'domcontentloaded' })
  await page.evaluate(s => {
    localStorage.clear()
    localStorage.setItem('panaceamed.session.v1', JSON.stringify(s))
    localStorage.setItem('panacea_onboarded_v1', '1')
    localStorage.setItem('panacea_assessment_prompt_v1', '1')
    localStorage.setItem('pmd_carbon_diet_v1', JSON.stringify({ beef: 7, rice: 0, pork: -1 }))
  }, session('carbon-a'))
  await page.goto(`${origin}/#/carbon-diet`, { waitUntil: 'domcontentloaded' })
  await page.reload({ waitUntil: 'domcontentloaded' })
  const beef = page.getByLabel(/Beef \(servings\/week\)/)
  const noEstimate = page.getByText('No estimate yet', { exact: true })
  assert.equal(await beef.inputValue(), '', 'legacy entries are not attributed to this account')
  await noEstimate.waitFor()
  await beef.fill('2')
  await page.getByText('Partial recorded-food estimate', { exact: true }).waitFor()
  await page.getByText('1169', { exact: true }).waitFor()
  assert.equal(await page.getByText('Average omnivore diet', { exact: true }).count(), 0, 'no full-diet comparison from partial entries')
  await beef.fill('')
  await noEstimate.waitFor()
  await page.waitForFunction(key => { const saved = JSON.parse(localStorage.getItem(key) || 'null'); return saved !== null && !Object.hasOwn(saved, 'beef') }, scopedKey('carbon-a'))
  for (const value of ['-1', '100.01']) {
    await beef.fill(value)
    await noEstimate.waitFor()
    await page.getByRole('alert').filter({ hasText: 'correct this field' }).waitFor()
  }
  await beef.fill('2.5')
  await page.getByText('1462', { exact: true }).waitFor()
  const inputs = page.locator('input[type=number]')
  assert.equal(await inputs.count(), 12)
  for (let i = 0; i < 12; i++) await inputs.nth(i).fill('0')
  await page.getByText('Your estimated footprint', { exact: true }).waitFor()
  await page.getByText('0', { exact: true }).waitFor()
  assert.equal(await noEstimate.count(), 0, 'explicit all-zero diet is representable')
  await beef.fill('2')
  await page.getByText('1169', { exact: true }).waitFor()
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key) || '{}').beef === 2, scopedKey('carbon-a'))
  await page.evaluate(s => localStorage.setItem('panaceamed.session.v1', JSON.stringify(s)), session('carbon-b'))
  await page.reload({ waitUntil: 'domcontentloaded' })
  assert.equal(await beef.inputValue(), '', 'B cannot see A entries')
  await noEstimate.waitFor()
  const other = await context.newPage()
  await other.goto(origin, { waitUntil: 'domcontentloaded' })
  await other.evaluate(s => localStorage.setItem('panaceamed.session.v1', JSON.stringify(s)), session('carbon-a'))
  await page.getByText('Session changed. Reopen this page after signing in.', { exact: true }).waitFor()
  await page.reload({ waitUntil: 'domcontentloaded' })
  assert.equal(await beef.inputValue(), '2', 'A data restored')
  await page.getByText('1169', { exact: true }).waitFor()
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('pmd_carbon_diet_v1'))), { beef: 7, rice: 0, pork: -1 }, 'legacy bytes untouched')
  assert.deepEqual(errors, [])
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  assert.ok(overflow <= 1)
  const evidence = { ok: true, synthetic: true, clientOnly: true, unknownNotZero: true, invalidEstimateSuppressed: true, explicitZeroAccepted: true, originalFactorsPreserved: true, partialEstimateLabelled: true, accountIsolation: true, crossTabMismatchBlocked: true, legacyNotAdopted: true, horizontalOverflowPx: overflow, clinicallyReviewed: false }
  await mkdir(output, { recursive: true })
  await writeFile(`${output}/evidence.json`, JSON.stringify(evidence, null, 2))
  console.log(JSON.stringify(evidence))
} finally { await browser.close() }
