import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '@playwright/test')
const origin = process.env.BODY_TOOLKIT_QA_ORIGIN || 'http://127.0.0.1:4173'
const output = process.env.BODY_TOOLKIT_QA_OUTPUT || 'artifacts/body-toolkit-storage'
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
const session = id => ({ account: { id, patientId: `self-${id}`, email: `${id}@localhost.test`, name: id, role: 'pasien', isSubscriber: false, loggedAt: new Date().toISOString() }, loginAt: Date.now() })
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  // Exercise a genuinely late lazy route without changing its asset or assertions.
  await page.route(/BodyToolkit-[^/]+\.js/, async route => { await new Promise(resolve => setTimeout(resolve, 250)); await route.continue() })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(origin, { waitUntil: 'domcontentloaded' })
  await page.evaluate(s => {
    localStorage.clear()
    localStorage.setItem('panaceamed.session.v1', JSON.stringify(s))
    localStorage.setItem('panacea_onboarded_v1', '1')
    localStorage.setItem('panacea_assessment_prompt_v1', '1')
    localStorage.setItem('pmd_symptom_map_v1', JSON.stringify([{ t: 1, region: 'Chest', severity: 9, note: 'unattributed legacy health data' }]))
  }, session('toolkit-a'))
  await page.goto(`${origin}/#/body-toolkit`, { waitUntil: 'domcontentloaded' })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Skincare Builder', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Symptom Map', exact: true }).click()
  assert.equal(await page.getByText(/9\/10 ·/).count(), 0, 'unattributed legacy symptoms must never be adopted by an account')
  await page.getByRole('button', { name: 'Log entry', exact: true }).click()
  await page.getByText(/3\/10 ·/).waitFor()
  await page.getByRole('button', { name: 'Skincare Builder', exact: true }).click()
  await page.getByRole('button', { name: '+ Cleanser', exact: true }).first().click()
  await page.getByRole('button', { name: 'NEAT Tracker', exact: true }).click()
  const minutes = page.getByLabel('Standing/walking minutes today')
  await minutes.fill('0')
  assert.equal(await minutes.inputValue(), '0', 'explicit zero remains visible')
  await minutes.fill('120')
  await page.evaluate(s => localStorage.setItem('panaceamed.session.v1', JSON.stringify(s)), session('toolkit-b'))
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Skincare Builder', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '+ Cleanser', exact: true }).count(), 2, 'B cannot see A morning skincare')
  await page.getByRole('button', { name: 'Symptom Map', exact: true }).click()
  assert.equal(await page.getByText(/3\/10 ·/).count(), 0, 'account B cannot see A symptoms')
  await page.getByRole('button', { name: 'NEAT Tracker', exact: true }).click()
  assert.equal(await minutes.inputValue(), '', 'account B cannot see A activity')
  await minutes.fill('60')
  // Replace the remembered session from another tab while A/B UI stays mounted.
  const other = await context.newPage()
  await other.goto(origin, { waitUntil: 'domcontentloaded' })
  await other.evaluate(s => localStorage.setItem('panaceamed.session.v1', JSON.stringify(s)), session('toolkit-a'))
  await page.getByText('Session changed. Reopen this page after signing in.', { exact: true }).waitFor()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Skincare Builder', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '+ Cleanser', exact: true }).count(), 1, 'A morning skincare restored')
  await page.getByRole('button', { name: 'NEAT Tracker', exact: true }).click()
  assert.equal(await minutes.inputValue(), '120', 'A data restored without B overwriting it')
  await page.getByRole('button', { name: 'Symptom Map', exact: true }).click()
  await page.getByText(/3\/10 ·/).waitFor()
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('pmd_symptom_map_v1'))[0].note), 'unattributed legacy health data', 'legacy bytes retained without silent migration')
  assert.deepEqual(errors, [])
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  assert.ok(overflow <= 1)
  await mkdir(output, { recursive: true })
  const evidence = { ok: true, synthetic: true, clientOnly: true, accountIsolation: true, crossTabMismatchBlocked: true, legacyNotAdopted: true, zeroVisible: true, horizontalOverflowPx: overflow, clinicallyReviewed: false }
  await writeFile(`${output}/evidence.json`, JSON.stringify(evidence, null, 2))
  console.log(JSON.stringify(evidence))
} finally { await browser.close() }
