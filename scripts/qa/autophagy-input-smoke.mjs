import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '@playwright/test')
const origin = process.env.AUTOPHAGY_QA_ORIGIN || 'http://127.0.0.1:4173'
const output = process.env.AUTOPHAGY_QA_OUTPUT || 'artifacts/autophagy-inputs'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    localStorage.clear()
    localStorage.setItem('panaceamed.session.v1', JSON.stringify({ account: {
      email: 'autophagy-qa@localhost.test', name: 'Synthetic input QA', role: 'pasien', isSubscriber: false,
      loggedAt: new Date().toISOString(),
    }, loginAt: Date.now() }))
    localStorage.setItem('panacea_onboarded_v1', '1')
    localStorage.setItem('panacea_assessment_prompt_v1', '1')
  })
  await page.goto(`${origin}/#/predictive-models-toolkit`)
  const fat = page.getByLabel(/^Body fat %/)
  const meal = page.getByLabel(/^Hours since last meal/)
  await fat.waitFor()
  assert.equal(await fat.inputValue(), '', 'body fat starts unknown')
  assert.equal(await meal.inputValue(), '', 'meal timing starts unknown')
  const noEstimate = page.getByText('No estimate yet', { exact: true })
  await noEstimate.waitFor()
  assert.equal(await page.getByLabel(/^Weight \(kg/).count(), 0, 'no unused weight field')
  await fat.fill('20')
  await noEstimate.waitFor()
  await meal.fill('2')
  await page.getByText('~10.4h', { exact: true }).waitFor()
  await meal.fill('')
  await noEstimate.waitFor()
  assert.equal(await page.getByText('~10.4h', { exact: true }).count(), 0, 'clearing a required value removes the estimate')
  await meal.fill('0')
  await page.getByText('~12.4h', { exact: true }).waitFor()
  await fat.fill('2.9')
  await noEstimate.waitFor()
  await page.getByText('Body fat must be within 3–70 %.', { exact: true }).waitFor()
  await fat.fill('20')
  await meal.fill('72.1')
  await noEstimate.waitFor()
  await page.getByText('Hours since last meal must be within 0–72 h.', { exact: true }).waitFor()
  await meal.fill('12.4')
  await page.getByText('Illustrative model threshold reached', { exact: true }).waitFor()
  await fat.fill('')
  await noEstimate.waitFor()
  assert.equal(await page.getByText('Illustrative model threshold reached', { exact: true }).count(), 0)
  await fat.fill('20')
  await meal.fill('2')
  await page.getByText('~10.4h', { exact: true }).waitFor()
  // The five other numeric inputs repaired in #2454 retain real model output
  // for valid data, suppress it when cleared, and recover without remounting.
  await page.getByRole('button', { name: 'Cortisol Curve', exact: true }).click()
  const curve = page.locator('svg[viewBox="0 0 300 100"] polyline')
  await curve.waitFor()
  assert.equal((await curve.getAttribute('points')).split(' ').length, 25)
  for (const label of [/^Daylight within/, /^Coffee within/]) {
    const field = page.getByLabel(label)
    const previous = await field.inputValue()
    await field.fill('')
    await noEstimate.waitFor()
    assert.equal(await curve.count(), 0, 'missing cortisol input removes curve')
    assert.equal(await field.getAttribute('aria-invalid'), 'true')
    await field.fill('0')
    await curve.waitFor()
    await field.fill('240.01')
    await noEstimate.waitFor()
    assert.equal(await curve.count(), 0, 'out-of-range cortisol input removes curve')
    await field.fill(previous)
    await curve.waitFor()
  }
  await page.getByRole('button', { name: 'Sauna Equivalent', exact: true }).click()
  const saunaOutput = page.getByText('≈ 16 min brisk walk', { exact: true })
  await saunaOutput.waitFor()
  for (const [label, invalid] of [[/^Session length/, '0'], [/^Temperature/, '110.01']]) {
    const field = page.getByLabel(label)
    const previous = await field.inputValue()
    await field.fill('')
    await noEstimate.waitFor()
    assert.equal(await saunaOutput.count(), 0, 'missing sauna input removes equivalent')
    await field.fill(invalid)
    await noEstimate.waitFor()
    assert.equal(await saunaOutput.count(), 0, 'invalid sauna input removes equivalent')
    await field.fill(previous)
    await saunaOutput.waitFor()
  }
  await page.getByRole('button', { name: 'Glycemic Load', exact: true }).click()
  const loadBand = page.getByText(/glycemic load$/, { exact: true })
  await loadBand.waitFor()
  const amount = page.getByLabel(/^Amount \(g/)
  const originalAmount = await amount.inputValue()
  await amount.fill('')
  await noEstimate.waitFor()
  assert.equal(await loadBand.count(), 0, 'empty food grams removes glycemic classification')
  await amount.fill('0')
  await noEstimate.waitFor()
  assert.equal(await loadBand.count(), 0, 'zero food grams is outside the declared range')
  await amount.fill(originalAmount)
  await loadBand.waitFor()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  assert.ok(overflow <= 1, `mobile horizontal overflow: ${overflow}px`)
  await page.getByRole('button', { name: 'Autophagy Timing', exact: true }).click()
  await noEstimate.waitFor()
  assert.deepEqual(errors, [], 'no browser runtime errors')
  const evidence = { ok: true, viewport: { width: 390, height: 844 }, initiallyMissing: true, goldenHours: 10.4, explicitZeroHours: 12.4, clearedValueDenied: true, outOfRangeDenied: true, recovery: true, allSevenInputs: true, cortisolSamples: 25, saunaGoldenMinutes: 16, horizontalOverflowPx: overflow, synthetic: true, clinicallyReviewed: false }
  await writeFile(`${output}/evidence.json`, JSON.stringify(evidence, null, 2))
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true })
  console.log(JSON.stringify(evidence))
} finally {
  await browser.close()
}
